import os, sys; sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "lib"))
import sys
from sleep_helpers import *
DATA = os.urandom(40000)
loader, m, ha, hc = setup()
print("== S4) the checkbox is available only while there are active downloads")
rpc("torrent-stop", ids=[1]); wait(lambda: torrents()["A_active.bin"] == 0, 10)
ok = wait(lambda: sstate()["stats"]["paused"] == 2 and sstate()["autosleep"]["can_arm"] is False, 20)
check("no active downloads -> 'can_arm: false'", ok, sstate()["autosleep"])
c, t = api("POST", "/api/autosleep", {"action": "arm", "timeout_minutes": 60}); j = json.loads(t)
check("arming is refused by the manager too, with a readable reason", c == 409 and "нет активных закачек" in j["message"], j["message"])
rpc("torrent-start", ids=[1]); check("a download starts -> arming becomes possible", wait(lambda: sstate()["autosleep"]["can_arm"] is True, 25), sstate()["autosleep"])
c, t = api("POST", "/api/autosleep", {"action": "arm", "timeout_minutes": 60}); a = sstate()["autosleep"]
check("armed with a 60 minute limit; editing the limit restarts it from now", c == 200 and a["armed"] and a["timeout_minutes"] == 60 and (api("POST", "/api/autosleep", {"action": "timeout", "minutes": 30}), sstate()["autosleep"])[1]["timeout_remaining"] > 1700)
check("nonsense limits are refused", api("POST", "/api/autosleep", {"action": "timeout", "minutes": 0})[0] == 409 and api("POST", "/api/autosleep", {"action": "arm", "timeout_minutes": 99999})[0] == 409)

print("== S5a) all downloads PAUSED by the user -> the checkbox switches itself off, the console stays awake")
before = suspends(); pid = daemon_pids()[0]; rpc("torrent-stop", ids=[1])
ok = wait(lambda: sstate()["autosleep"]["armed"] is False, 45)
check("the auto-sleep switched itself off", ok and "switched off: the downloads were paused or removed" in shim(), "")
time.sleep(6); check("no sleep, Transmission untouched, no countdown", suspends() == before and daemon_pids() == [pid] and sstate()["sleep"]["phase"] == "idle", f"suspends {before}->{suspends()}")

print("== S5b) all downloads DELETED by the user -> the same")
rpc("torrent-start", ids=[1]); wait(lambda: sstate()["autosleep"]["can_arm"], 25)
api("POST", "/api/autosleep", {"action": "arm", "timeout_minutes": 60}); time.sleep(6); rpc("torrent-remove", ids=[1])
ok = wait(lambda: sstate()["autosleep"]["armed"] is False, 45)
time.sleep(4); check("switched itself off after the removal, no sleep", ok and suspends() == before and daemon_pids() == [pid], f"suspends {before}->{suspends()}")

print("== S5c) a download really FINISHES -> the console goes to sleep")
api("POST", "/api/config", {"sleep_notify_before": False})
rid = add_real_torrent("R_real.bin", DATA); check("a real download is running", wait(lambda: sstate()["autosleep"]["can_arm"], 25))
api("POST", "/api/autosleep", {"action": "arm", "timeout_minutes": 60}); time.sleep(7)
check("while it downloads nothing happens", suspends() == before and sstate()["autosleep"]["armed"])
finish_real_torrent(rid, "R_real.bin", DATA)
ok = wait(lambda: suspends() > before, 70)
check("after the download completed the console went to sleep", ok and "auto-sleep triggered (all downloads finished)" in shim(), "")
check("the job switched itself off; Transmission was stopped like by the button", sstate()["autosleep"]["armed"] is False and not daemon_pids() and "Transmission stopped before sleep." in mgrlog())
wake(); wait(lambda: daemon_pids() and rpc_ok() and dstate()["state"] == "running", 60)
kill_all(); loader.close()
sys.exit(summary())
