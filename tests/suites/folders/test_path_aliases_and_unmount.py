import os, sys; sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "lib"))
import sys, json, time, os, re, base64, hashlib, subprocess, shutil
os.environ["PS5TM_TEST_ALIAS"] = "/data/ext1=/mnt/ext1;/data/usb0=/mnt/usb0"   # there is no nullfs on the host: the alias table looks like BindMount (both the manager and the daemon read it)
from harness import *
def sh(c): return subprocess.run(c, shell=True, capture_output=True, text=True)
def meta(name): return base64.b64encode(bencode({"announce": "http://127.0.0.1:1/announce", "info": {"name": name, "length": 65536, "piece length": 65536, "pieces": hashlib.sha1(name.encode()).digest()}})).decode()
def add(name, folder): return rpc("torrent-add", metainfo=meta(name), **{"download-dir": folder})
def ok(r): return r["result"] == "success"
def fpost(**b): return api("POST", "/api/folders", b)
def folders(): return {f["path"]: f for f in json.loads(api("GET", "/api/folders")[1])["folders"]}
def bell(): c, t = api("GET", "/api/notifications"); return [i["text"] for i in json.loads(t)["items"]] if c == 200 else []
def mounted(p): return any(l.split()[1] == p for l in open("/proc/self/mounts"))
def status(name): return [t["status"] for t in rpc("torrent-get", fields=["name", "status"])["arguments"]["torrents"] if t["name"] == name]
def cleanup():
    for d in ("/mnt/usb0", "/mnt/usb2", "/mnt/usb3", "/mnt/ext1"): sh(f"umount {d} 2>/dev/null; rm -rf {d}")
    sh("rm -rf /data/ext1 /data/usb0 /data/torrents")
def mount(d): os.makedirs(d, exist_ok=True); sh(f"mount -t tmpfs -o size=64m tmpfs {d}")
cleanup(); shutil.rmtree("/user/app", ignore_errors=True); os.makedirs("/user/app")
for d in ("/mnt/usb2", "/mnt/usb3", "/mnt/ext1", "/mnt/usb0"): mount(d)
os.makedirs("/data/ext1/torrents", exist_ok=True); os.makedirs("/data/usb0/dl", exist_ok=True); os.makedirs("/data/torrents", exist_ok=True)
fresh(); loader = Loader(); m = start_manager()
try:
    wait(lambda: daemon_pids() and rpc_ok() and dstate()["state"] == "running", 70); time.sleep(3)
    print("== a path through an alias (nullfs: /data/ext1 is /mnt/ext1) is recognised through the system, nothing is hard-coded")
    for p in ("/data/ext1/torrents", "/data/usb0/dl", "/data/torrents", "/mnt/usb2/torrents", "/mnt/usb3/torrents"):
        c, t = fpost(action="add", path=p, confirm=True)
        if c != 200: print("   add failed:", p, c, t[:100])
    f = folders()
    check("/data/ext1/torrents is a M.2 SSD (kind ssd), /data/usb0/dl a USB drive, /data/torrents still internal", f["/data/ext1/torrents"]["kind"] == "ssd" and f["/data/usb0/dl"]["kind"] == "usb" and f["/data/torrents"]["kind"] == "int", {k: v["kind"] for k, v in f.items()})
    check("their disks are reported as connected (the real disks /mnt/ext1 and /mnt/usb0 are mounted)", f["/data/ext1/torrents"]["mounted"] is True and f["/data/usb0/dl"]["mounted"] is True, None)
    check("the daemon accepts a torrent into the alias folder while the real disk is mounted", ok(add("al_one", "/data/usb0/dl")), None)
    rpc("torrent-remove", ids=[t["id"] for t in rpc("torrent-get", fields=["name", "id"])["arguments"]["torrents"] if t["name"] == "al_one"])
    sh("umount /mnt/usb0")
    r = add("al_two", "/data/usb0/dl")
    check("with the real disk unplugged the DAEMON refuses the alias folder (it sees through the alias that the disk /mnt/usb0 is missing)", not ok(r) and "/mnt/usb0" in r["result"] and "not connected" in r["result"], r["result"][:120])
    check("and the page shows that folder as 'not connected'", folders()["/data/usb0/dl"]["mounted"] is False, None)
    mount("/mnt/usb0")
    print("== 'Unmount the drive' on a folder of a USB drive")
    check("a torrent is running on the USB drive", ok(add("um_one", "/mnt/usb2/torrents")) and wait(lambda: status("um_one") and status("um_one")[0] != 0, 10), status("um_one"))
    c, t = fpost(action="unmount", path="/mnt/usb2/torrents"); j = json.loads(t)
    check("unmount: 200, the message says the drive is unmounted, the mount is gone", c == 200 and j.get("ok") and "размонтирован" in j.get("message", "") and not mounted("/mnt/usb2"), (c, t[:200]))
    check("the torrents of that drive were stopped first (status 0) and the bell has the entry", status("um_one") == [0] and any("размонтирован" in x for x in bell()), (status("um_one"), [x[:50] for x in bell()][-2:]))
    f = folders()
    check("the folder row is now 'not connected'", f["/mnt/usb2/torrents"]["mounted"] is False, None)
    c, t = fpost(action="unmount", path="/mnt/usb2/torrents")
    check("unmounting a drive that is not connected is refused with a clear message", c == 409 and "Диск не подключён" in t, (c, t[:120]))
    print("== a busy drive is not forced")
    hold = open("/mnt/usb3/hold.txt", "w"); hold.write("x")
    t0 = time.time(); c, t = fpost(action="unmount", path="/mnt/usb3/torrents")
    check("an open file on the drive: 409 'drive is busy' after the retries (a few seconds), the drive stays mounted", c == 409 and "занят" in t and mounted("/mnt/usb3") and time.time() - t0 >= 2, (c, t[:160], f"{time.time()-t0:.1f}s"))
    check("the busy refusal is in the bell as well", any("занят" in x for x in bell()), None)
    hold.close()
    c, t = fpost(action="unmount", path="/mnt/usb3/torrents")
    check("after the file is closed the same request unmounts the drive", c == 200 and not mounted("/mnt/usb3"), (c, t[:120]))
    print("== only USB drives, also through an alias")
    c1, t1 = fpost(action="unmount", path="/data/ext1/torrents"); c2, t2 = fpost(action="unmount", path="/data/torrents"); c3, t3 = fpost(action="unmount", path="/nonsense")
    check("a M.2 SSD (even through the alias /data/ext1), an internal folder and an unknown path are refused; nothing is unmounted", c1 == 409 and "только USB-диск" in t1 and c2 == 409 and "только USB-диск" in t2 and c3 == 409 and "только USB-диск" in t3 and mounted("/mnt/ext1"), (c1, c2, c3))
    c, t = fpost(action="unmount", path="/data/usb0/dl")
    check("a folder reached through the alias /data/usb0 unmounts the real drive /mnt/usb0", c == 200 and not mounted("/mnt/usb0"), (c, t[:150]))
finally:
    kill_all(); cleanup()
    try: loader.close()
    except Exception: pass
sys.exit(summary())
