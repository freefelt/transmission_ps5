print("== 8) the PS5 situation: the daemon hangs (RPC stops answering) while the network is up")
os.kill(pid0, signal.SIGSTOP); t0 = time.time()
check("the daemon really does not answer now", not rpc_ok())
ok = wait(lambda: daemon_pids() and daemon_pids()[0] != pid0 and rpc_ok(), 80)
dt = time.time() - t0
check("the manager restarted it on its own and the web UI is back", ok, f"{dt:.0f} s, new pid {daemon_pids()}")
check("the hung process is gone (not left behind)", pid0 not in daemon_pids())
check("exactly one more launch through the loader", loader.count == 2, loader.count)
check("a snapshot for diagnostics was written before the restart", "diag (restarting the daemon)" in shim() or "diag (daemon not responding)" in shim())
wait(lambda: "Transmission restarted." in mgrlog(), 15)
check("only 'restarted' is announced: the 'not responding' notification is gone", "not responding" not in mgrlog() and "Restarting it" not in mgrlog() and "Transmission restarted." in mgrlog())
time.sleep(4); check("the torrent that was active before the hang is active again (Transmission restores its state)", torrents().get("A_active.bin", 0) != 0, torrents())
print("== 9) the daemon crashes (killed)")
pid1 = daemon_pids()[0]; os.kill(pid1, signal.SIGKILL); t0 = time.time()
ok = wait(lambda: daemon_pids() and daemon_pids()[0] != pid1 and rpc_ok(), 70)
check("the supervisor starts it again", ok, f"{time.time()-t0:.0f} s")
