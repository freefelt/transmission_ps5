#!/usr/bin/env python3
"""Page (jsdom) and web (Chrome) tests against the real manager and daemon. Results as lines in /tmp/ps5tm-test-pages.txt.
Run: scripts/test.sh pages [segment...] (needs root for tmpfs, free ports 9091/9092, the test binaries from tests/build/build-test-binaries.sh and the files generated by ./build.sh)."""
import os, sys; sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "lib"))
import sys, subprocess, os, time, json
from harness import *
import web_stack
OUT = "/tmp/ps5tm-test-pages.txt"
def log(s):
    open(OUT, "a", encoding="utf-8").write(s + "\n")
FAILED = False   # any test of the run failed or crashed: the exit status of the script
def node(*a, t=250):
    global FAILED
    t0 = time.time()
    r = subprocess.run(["node", *a], cwd=WEB_TESTS, capture_output=True, text=True, timeout=t)
    dt = int(time.time() - t0)
    lines = [l[:260] for l in r.stdout.split("\n") if l.startswith("FAIL") or "passed" in l or "crashed" in l]
    if r.returncode != 0 or any(l.startswith("FAIL") or "crashed" in l for l in lines):
        FAILED = True
    log(" ".join(a) + " | " + " || ".join(lines) + (" | stderr: " + r.stderr[-150:] if r.stderr.strip() else "") + f" [{dt} s]")
def sh(c): subprocess.run(c, shell=True, capture_output=True)
SEG = set(sys.argv[1:]) or {"settings", "daemon-card", "sleep", "webui", "effects"}
open(OUT, "w").close()
def clean_mounts():
    for i in range(8): sh(f"umount /mnt/usb{i} /mnt/ext{i} 2>/dev/null")
def stack_up():
    fresh(); loader = Loader(); m = start_manager(); wait(lambda: daemon_pids() and rpc_ok() and dstate()["state"] == "running", 70); time.sleep(8); return loader
def seg_a():   # settings page (needs the mounted disk /mnt/usb2)
    clean_mounts(); sh("rm -rf /user/app /tmp/ps5_usb1 /tmp/ps5tm_icon_*; mkdir -p /user/app /mnt/usb2 /mnt/usb3; mount -t tmpfs -o size=64m tmpfs /mnt/usb2")
    loader = stack_up(); add_torrent("A_active.bin", False); add_torrent("C_paused_by_user.bin", True); time.sleep(8)
    api("POST", "/api/config", {"notify_startup": False}); api("POST", "/api/daemon", {"action": "stop"}); wait(lambda: dstate()["state"] == "stopped", 45)
    api("POST", "/api/daemon", {"action": "start"}); wait(lambda: daemon_pids() and rpc_ok() and dstate()["state"] == "running", 80); time.sleep(12)
    api("POST", "/api/config", {"notify_startup": True}); wait(lambda: json.loads(api("GET", "/api/state")[1])["autosleep"]["can_arm"], 30)
    api("POST", "/api/autosleep", {"action": "arm"}); time.sleep(1); api("POST", "/api/autosleep", {"action": "disarm"})
    api("POST", "/api/folders", {"action": "remove", "path": "/data/torrents"})   # a fresh installation: the list is empty, the torrents (added above) stay
    node("settings_page_test.js", t=290); kill_all(); loader.close(); clean_mounts(); sh("rm -rf /mnt/usb2 /mnt/usb3 /data/pagetest")
def seg_b():   # the daemon card and the icon card (clean state)
    sh("rm -rf /user/app /tmp/ps5_usb1 /tmp/ps5tm_icon_*; mkdir -p /user/app"); loader = stack_up()
    node("daemon_card_test.js"); node("icon_page_test.js"); node("update_notice_test.js"); kill_all(); loader.close()
    if os.path.exists("/tmp/ps5tm_icon_mode"): os.remove("/tmp/ps5tm_icon_mode")
def seg_c():   # the sleep block
    sh("rm -rf /user/app /tmp/ps5_usb1 /tmp/ps5tm_icon_*; mkdir -p /user/app"); loader = stack_up(); add_torrent("C_paused_by_user.bin", True)
    node("sleep_page_test.js", "A"); add_torrent("A_active.bin", False); time.sleep(10); node("sleep_page_test.js", "B"); kill_all(); loader.close()
def seg_d():   # the Transmission web interface in Chrome (web_stack stand: torrents, tmpfs disks)
    sh("rm -rf /user/app /tmp/ps5_usb1 /tmp/ps5tm_icon_*; mkdir -p /user/app")
    loader = web_stack.setup(); time.sleep(4)
    for th in ("dark", "light"):
        api("POST", "/api/config", {"web_theme": th}); time.sleep(1); node("ui_filter_test.js"); node("ui_layout_test.js")
    api("POST", "/api/config", {"web_theme": "dark"}); time.sleep(1)
    node("ui_panel_test.js", "A", "color"); node("ui_select_dialog_test.js"); node("ui_console_test.js"); node("ui_dir_test.js"); node("ui_usbfix_test.js")
    api("POST", "/api/config", {"web_icons": "color"}); time.sleep(1); node("ui_icons_test.js", "color")
    api("POST", "/api/config", {"web_icons": "mono"}); time.sleep(1); node("ui_icons_test.js", "mono"); node("ui_panel_test.js", "A", "mono")
    api("POST", "/api/config", {"web_icons": "color"}); time.sleep(1)
    ts = rpc("torrent-get", fields=["id", "downloadDir"])["arguments"]["torrents"]
    rpc("torrent-remove", ids=[t["id"] for t in ts if t["downloadDir"] != "/data/torrents"]); node("ui_panel_test.js", "B")
    rpc("torrent-remove", ids=[t["id"] for t in rpc("torrent-get", fields=["id"])["arguments"]["torrents"]]); node("ui_panel_test.js", "C")
    api("POST", "/api/config", {"web_diskbar": "off"}); time.sleep(1); node("ui_panel_test.js", "D")
    node("ui_panel_modes_test.js")
    node("ui_openfolder_test.js")
    node("ui_tiles_test.js")
    kill_all(); loader.close(); clean_mounts(); sh("rm -rf /mnt/ext1 /mnt/usb0")
def seg_e():   # animation of showing and hiding the sections on the settings page (real Chrome)
    sh("rm -rf /user/app /tmp/ps5_usb1 /tmp/ps5tm_icon_*; mkdir -p /user/app"); sh("for d in /mnt/ext1 /mnt/usb2; do umount $d 2>/dev/null; rm -rf $d; mkdir -p $d; mount -t tmpfs -o size=64m tmpfs $d; done; for i in $(seq 1 35); do mkdir -p /mnt/ext1/Folder_$i; done; mkdir -p /mnt/usb2/Games"); loader = stack_up()
    node("ui_anim_test.js"); node("ui_popup_anim_test.js"); node("ui_tint_test.js"); node("ui_picker_test.js"); node("ui_sleepquit_test.js"); kill_all(); loader.close(); sh("umount /mnt/ext1 2>/dev/null; umount /mnt/usb2 2>/dev/null; rm -rf /mnt/ext1 /mnt/usb2")
def seg_f():   # language selection: the page is English by default (as in a real installation), the file comes from the locales folder
    import harness; harness.TEST_LANG = None
    sh("rm -rf /user/app /tmp/ps5_usb1 /tmp/ps5tm_icon_* /data/Transmission/locales; mkdir -p /user/app")
    loader = stack_up()
    os.makedirs("/data/Transmission/locales", exist_ok=True)
    open("/data/Transmission/locales/es.strings", "w", encoding="utf-8").write('"LanguageName" = "Español"\n"exit_transmission" = "Salir de Transmission"\n"save" = "Guardar"\n"download_folders" = "Carpetas de descarga"\n')
    node("ui_lang_test.js"); kill_all(); loader.close(); sh("rm -rf /data/Transmission/locales")
    harness.TEST_LANG = "ru"
def seg_g():   # the Transmission web client (port 9091) in Russian and English: the translation is inside the client code (ps5t); the language comes from the setting, messages without the mixed mode
    import harness; harness.TEST_LANG = None; harness.TEST_MSG = None
    sh("rm -rf /user/app /tmp/ps5_usb1 /tmp/ps5tm_icon_*; mkdir -p /user/app")
    sh("for d in /mnt/ext1 /mnt/usb2; do umount $d 2>/dev/null; rm -rf $d; mkdir -p $d; mount -t tmpfs -o size=64m tmpfs $d; done; mkdir -p /mnt/usb2/torrents /mnt/ext1/torrents")
    loader = stack_up()
    node("ui_web_lang_test.js"); node("ui_inspector_test.js"); node("ui_motion_test.js"); kill_all(); loader.close(); sh("umount /mnt/ext1 2>/dev/null; umount /mnt/usb2 2>/dev/null; rm -rf /mnt/ext1 /mnt/usb2")
    harness.TEST_LANG = "ru"; harness.TEST_MSG = "mixed"
for name, fn in (("settings", seg_a), ("daemon-card", seg_b), ("sleep", seg_c), ("webui", seg_d), ("effects", seg_e), ("language", seg_f), ("webui-language", seg_g)):
    if name in SEG:
        t0 = time.time(); fn(); log(f"SEGMENT {name}: {int(time.time() - t0)} s (stack start, tests and clean-up)")
log("ALL DONE")
sys.exit(1 if FAILED else 0)
